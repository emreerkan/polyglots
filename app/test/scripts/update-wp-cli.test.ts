import { describe, expect, it } from 'vitest'
import { pharAssets, parseSha512, pinnedVersion, renderPin } from '../../scripts/update-wp-cli.mjs'
import { WP_CLI } from '../../src/lint/wp-cli-pin.js'

const HEX = 'be928f6b'.repeat(16)
const asset = (name: string, size = 10) => ({ name, size, browser_download_url: `https://github.com/wp-cli/wp-cli/releases/download/v2.12.0/${name}` })

describe('pharAssets', () => {
  it('picks the phar and its .sha512 from the latest release', () => {
    const release = { tag_name: 'v2.12.0', assets: [asset('wp-cli-2.12.0.phar.md5'), asset('wp-cli-2.12.0.phar', 7142777), asset('wp-cli-2.12.0.phar.sha512')] }
    expect(pharAssets(release)).toEqual({
      version: '2.12.0',
      url: 'https://github.com/wp-cli/wp-cli/releases/download/v2.12.0/wp-cli-2.12.0.phar',
      size: 7142777,
      sha512Url: 'https://github.com/wp-cli/wp-cli/releases/download/v2.12.0/wp-cli-2.12.0.phar.sha512',
    })
  })
  it('refuses a release without a published .sha512', () => {
    expect(() => pharAssets({ tag_name: 'v2.12.0', assets: [asset('wp-cli-2.12.0.phar')] })).toThrow(/\.sha512/)
  })
  it('refuses a tag that is not a version', () => {
    expect(() => pharAssets({ tag_name: 'nightly', assets: [] })).toThrow(/nightly/)
  })
})

describe('parseSha512', () => {
  it('reads the hash alone or followed by a file name', () => {
    expect(parseSha512(`${HEX}\n`)).toBe(HEX)
    expect(parseSha512(`${HEX.toUpperCase()}  wp-cli-2.12.0.phar\n`)).toBe(HEX)
  })
  it('refuses anything that is not a SHA-512', () => {
    expect(() => parseSha512('not a hash')).toThrow(/SHA-512/)
  })
})

describe('renderPin', () => {
  it('writes a file whose version can be read back', () => {
    const text = renderPin({ version: '2.12.0', url: 'https://x/wp-cli-2.12.0.phar', sha512: HEX, size: 7142777 })
    expect(text).toMatch(/^\/\/ Generated by scripts\/update-wp-cli\.mjs/)
    expect(pinnedVersion(text)).toBe('2.12.0')
    expect(text).toContain(`sha512: '${HEX}'`)
  })
})

describe('the committed pin', () => {
  it('names a phar of its own version with a full SHA-512', () => {
    expect(WP_CLI.url).toBe(`https://github.com/wp-cli/wp-cli/releases/download/v${WP_CLI.version}/wp-cli-${WP_CLI.version}.phar`)
    expect(WP_CLI.sha512).toMatch(/^[0-9a-f]{128}$/)
    expect(WP_CLI.size).toBeGreaterThan(1_000_000)
  })
})
