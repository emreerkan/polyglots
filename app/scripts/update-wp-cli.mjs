#!/usr/bin/env node
// Refreshes src/lint/wp-cli-pin.ts, the WP-CLI phar polyglots lint downloads
// when no wp command is installed, from the latest wp-cli/wp-cli release.
//
// The phar is never packaged: it is seven megabytes most installs never use.
// It is downloaded on first use and checked against the SHA-512 kept in the
// pin, so a compromised download is refused rather than run. This script is
// the one place that hash is decided. It downloads the phar and the .sha512
// the WP-CLI maintainers publish beside it, hashes the phar itself, and
// writes the pin only when the two agree.
//
// Run on purpose, with npm run update-wp-cli, and the result committed, like
// update-locales: a new WP-CLI arrives as a reviewed diff with the tests run
// against it, never underneath a release. Unlike update-locales it fails
// loudly: there is no stale-but-right answer to fall back on when the hashes
// disagree.

import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const LATEST = 'https://api.github.com/repos/wp-cli/wp-cli/releases/latest'
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'lint', 'wp-cli-pin.ts')
const HEADERS = { 'User-Agent': 'polyglots update-wp-cli (+https://github.com/emreerkan/polyglots)' }

/** The phar and .sha512 assets of a GitHub release object. */
export function pharAssets(release) {
  const version = String(release.tag_name ?? '').replace(/^v/, '')
  if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error(`the latest release is tagged ${release.tag_name}, not a version`)
  const find = (name) => (release.assets ?? []).find((a) => a.name === name)
  const phar = find(`wp-cli-${version}.phar`)
  const sum = find(`wp-cli-${version}.phar.sha512`)
  if (!phar || !sum) throw new Error(`release v${version} has no wp-cli-${version}.phar with a .sha512 beside it`)
  return { version, url: phar.browser_download_url, size: phar.size, sha512Url: sum.browser_download_url }
}

/** The hash in a .sha512 file: alone, or followed by the file name. */
export function parseSha512(text) {
  const hex = (text.trim().split(/\s+/)[0] ?? '').toLowerCase()
  if (!/^[0-9a-f]{128}$/.test(hex)) throw new Error('the .sha512 file holds no SHA-512')
  return hex
}

export function renderPin(pin) {
  return `// Generated by scripts/update-wp-cli.mjs. Do not edit by hand: npm run
// update-wp-cli rewrites it, after checking the phar against the .sha512 the
// WP-CLI maintainers publish beside it. polyglots lint downloads this phar
// only when no wp command is installed, and refuses it unless it hashes to
// sha512 below.

export const WP_CLI = {
  version: '${pin.version}',
  url: '${pin.url}',
  sha512: '${pin.sha512}',
  size: ${pin.size},
}
`
}

export function pinnedVersion(source) {
  return /version: '([^']+)'/.exec(source)?.[1]
}

async function download(url) {
  const res = await fetch(url, { headers: HEADERS })
  if (!res.ok) throw new Error(`${url} answered ${res.status}`)
  return Buffer.from(await res.arrayBuffer())
}

async function main() {
  try {
    const res = await fetch(LATEST, { headers: { ...HEADERS, Accept: 'application/vnd.github+json' } })
    if (!res.ok) throw new Error(`GitHub answered ${res.status}`)
    const assets = pharAssets(await res.json())
    let current = ''
    try {
      current = readFileSync(OUT, 'utf8')
    } catch {}
    const was = pinnedVersion(current)
    if (was === assets.version) {
      console.log(`update-wp-cli: ${was} is already pinned`)
      return
    }
    const [phar, sum] = await Promise.all([download(assets.url), download(assets.sha512Url)])
    const published = parseSha512(sum.toString('utf8'))
    const computed = createHash('sha512').update(phar).digest('hex')
    if (computed !== published) throw new Error(`the phar hashes to ${computed}, but the published .sha512 says ${published}`)
    if (phar.length !== assets.size) throw new Error(`the phar is ${phar.length} bytes, but the release lists ${assets.size}`)
    writeFileSync(OUT, renderPin({ version: assets.version, url: assets.url, sha512: computed, size: phar.length }))
    console.log(`update-wp-cli: ${was ?? 'none'} -> ${assets.version}, wrote src/lint/wp-cli-pin.ts`)
  } catch (err) {
    console.error(`update-wp-cli: kept the pin (${err instanceof Error ? err.message : err})`)
    process.exitCode = 1
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main()
