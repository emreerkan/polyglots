#!/usr/bin/env node
// Bundles the glossary editor page's browser code
// (src/glossary/editor/page/entry.ts and what it imports) into the committed
// src/glossary/editor/client-bundle.ts, as one string.
//
// The same arrangement as scripts/stats-client.mjs, for the same reasons: the
// local server inlines the script into the one page it serves, TypeScript
// cannot produce that single file on its own, and the model and CSV code are
// shared with the CLI. The output is committed so a published package never
// needs esbuild at run time; a test fails when it is stale.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const ENTRY = join(ROOT, 'src', 'glossary', 'editor', 'page', 'entry.ts')
const OUT = join(ROOT, 'src', 'glossary', 'editor', 'client-bundle.ts')

export async function bundleClient() {
  const result = await build({
    entryPoints: [ENTRY],
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    target: 'es2022',
    minify: true,
    legalComments: 'none',
    charset: 'utf8',
    logLevel: 'silent',
  })
  return result.outputFiles[0].text.trimEnd()
}

export function renderBundleModule(code) {
  return `// Generated by scripts/glossary-client.mjs from src/glossary/editor/page. Do
// not edit by hand: change the page code and run npm run glossary-client.

export const EDITOR_JS = ${JSON.stringify(code)}
`
}

async function main() {
  const next = renderBundleModule(await bundleClient())
  let current = ''
  try {
    current = readFileSync(OUT, 'utf8')
  } catch {}
  if (current === next) {
    console.log('glossary-client: unchanged')
    return
  }
  writeFileSync(OUT, next)
  console.log(`glossary-client: wrote ${Math.round(next.length / 1024)} KB to src/glossary/editor/client-bundle.ts`)
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main()
